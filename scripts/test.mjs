import assert from 'node:assert/strict';
import fs from 'node:fs';
import {prepare,filterRows,matches,csvValue} from '../search.js';
const data=JSON.parse(fs.readFileSync(new URL('../data/boneinfo.json',import.meta.url)));
const db=prepare(data);const query=f=>filterRows(db.rows,f,db.periods);
assert.equal(db.rows.length,2434);
assert.equal(db.rows.reduce((n,c)=>n+c.species.length,0),28808);
assert.equal(db.rows.reduce((n,c)=>n+c.publications.length,0),4593);
assert.equal(db.rows.flatMap(c=>c.species).filter(s=>!s.taxon).length,17);
assert.equal(query({}).length,2434);
assert.equal(query({cluster:'15'})[0].Plaats,'Malden');
assert.equal(db.byId.get('15').species[0].taxon.lat_omschrijving,'Homo sapiens');
assert.ok(query({q:'Lauwerier'}).some(c=>c.Zoonr==='19'));
assert.ok(query({species:'Homo sapiens',province:'Gelderland'}).some(c=>c.Zoonr==='15'));
assert.ok(query({place:'Nijmegen',species:'rund'}).length>0);
assert.ok(query({place:'Nijmegen',species:'rund'}).every(c=>c.Plaats.includes('Nijmegen')||c.Gemeente.includes('Nijmegen')));
assert.equal(query({q:'zzzznietbestaand'}).length,0);
assert.equal(query({from:'1500',to:'1000'}).length,0);
assert.ok(query({from:'-1800',to:'-1800'}).some(c=>c.Zoonr==='15'));
assert.ok(!query({from:'-1100',to:'-1100'}).some(c=>c.Zoonr==='15'));
assert.ok(query({period:'BRONSM'}).some(c=>c.Zoonr==='15'));
assert.equal(db.byId.get('1264').start,1250);
assert.ok(query({period:'Onbekend'}).every(c=>c.Begin_periode==='Onbekend'||c.Eind_periode==='Onbekend'));
assert.ok(matches('Archeozoölogie Cervus elaphus','archeozoologie cerv*'));
assert.ok(matches('rund','r?nd'));assert.ok(!matches('rund','r.nd'));
assert.equal(csvValue('="unsafe"'), '"\'=\"\"unsafe\"\""');
assert.equal(csvValue('-1800'),'"-1800"');
console.log('PASS: relational completeness, unknown taxa, text/wildcards, combined filters, period overlap, zero-year fallback and CSV escaping.');
